"""Generates THIRD_PARTY_NOTICES_RUST.md from `cargo metadata` of the pinned libDF build (D-026):
every crate in deep_filter's normal-dependency closure with name, version, licence expression,
and all LICENSE*/COPYING*/NOTICE* files from its source (identical texts de-duplicated).
Usage: python3 -I scripts/gen_rust_notices.py   (after scripts/build_libdf.sh)"""
import hashlib
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "vendor/libdf/src")
env = dict(os.environ, PATH=os.path.expanduser("~/.cargo/bin") + ":" + os.environ["PATH"])
meta = json.loads(subprocess.run(["cargo", "+1.88.0", "metadata", "--format-version", "1", "--locked",
                                  "--filter-platform", "aarch64-apple-darwin"], cwd=SRC, env=env,
                                 capture_output=True, text=True, check=True).stdout)
pk = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
root = next(p["id"] for p in meta["packages"] if p["name"] == "deep_filter")
seen, stack = set(), [root]
while stack:
    i = stack.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] in (None, "normal") for k in d["dep_kinds"]):
            stack.append(d["pkg"])

texts, rows = {}, []
for i in sorted(seen, key=lambda x: (pk[x]["name"], pk[x]["version"])):
    p = pk[i]
    d = os.path.dirname(p["manifest_path"])
    refs = []
    for f in sorted(os.listdir(d)):
        if f.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")) and os.path.isfile(os.path.join(d, f)):
            t = open(os.path.join(d, f), encoding="utf-8", errors="replace").read().strip()
            h = hashlib.sha256(t.encode()).hexdigest()[:12]
            texts.setdefault(h, (f, t))
            refs.append(h)
    rows.append((p["name"], p["version"], p.get("license") or "see file", p.get("repository") or "", refs, ", ".join(p.get("authors") or [])))

out = ["# Third-party notices — Rust crates in libDF (DeepFilterNet Plus)", "",
       "Generated by `scripts/gen_rust_notices.py` from the pinned build (`scripts/build_libdf.sh`).",
       "These crates are statically linked into `libdf.dylib` (the list is a superset: it ignores Cargo features, so e.g. the training-only hdf5 crates appear), which LectureLift loads at runtime for the",
       "optional \"Qualität\" (denoise) mode. Licence texts follow below, identical texts once.", "",
       "| Crate | Version | Licence | Source | Licence texts |", "|---|---|---|---|---|"]
for n, v, l, r, refs, a in rows:
    shipped = ", ".join("T-" + h for h in refs)
    if not shipped:
        # no licence file in the crate: copyright holders from Cargo.toml + the standard texts below
        shipped = f"none shipped; © {a or 'the ' + n + ' authors'}; standard texts: see MIT / Apache-2.0 below"
    out.append(f"| {n} | {v} | {l} | {r} | {shipped} |")
out += ["", "## Licence texts", ""]
for h, (f, t) in texts.items():
    out += [f"### T-{h} ({f})", "", "```", t, "```", ""]
open(os.path.join(ROOT, "THIRD_PARTY_NOTICES_RUST.md"), "w").write("\n".join(out))
print(f"{len(rows)} crates, {len(texts)} distinct licence texts → THIRD_PARTY_NOTICES_RUST.md")
